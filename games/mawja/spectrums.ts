export function drawRandomSpectrums(
  count: number,
  excludeIds: string[] = []
): MawjaSpectrum[] {
  const available = MAWJA_SPECTRUMS.filter((s) => !excludeIds.includes(s.id));
  const pool = available.length >= count ? available : [...MAWJA_SPECTRUMS];
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getSpectrumById(id: string): MawjaSpectrum | undefined {
  return MAWJA_SPECTRUMS.find((s) => s.id === id);
}
